#!/usr/bin/env python3
"""Import declarative schemas, including codec fields, from pinned libtiff.
No parser or codec implementation is imported. Every table row is accounted for;
only explicitly ignored fields and pseudo tags (not on-file tags) are omitted.
"""
import argparse
import pathlib
import re

root = pathlib.Path(__file__).resolve().parents[1]
source = root / '.tools/tiff-4.7.1/libtiff'
kind = {'UINT8': ('TIFF_BYTE', 1), 'SINT8': ('TIFF_SBYTE', 1),
        'UINT16': ('TIFF_SHORT', 2), 'SINT16': ('TIFF_SSHORT', 2),
        'UINT32': ('TIFF_LONG', 4), 'SINT32': ('TIFF_SLONG', 4),
        'UINT64': ('TIFF_LONG8', 8), 'SINT64': ('TIFF_SLONG8', 8),
        'IFD8': ('TIFF_IFD8', 8), 'FLOAT': ('TIFF_FLOAT', 4),
        'DOUBLE': ('TIFF_DOUBLE', 8), 'ASCII': ('TIFF_ASCII', 1)}
counts = {'TIFF_VARIABLE': '-1', 'TIFF_VARIABLE2': '-3', 'TIFF_SPP': '-2'}

def tables(path):
    text = re.sub(r'/\*.*?\*/|//[^\n]*', '', path.read_text(), flags=re.S)
    # Retain the standard declarative DNG/EP schemas previously supported here,
    # even where the upstream build disables them with #if 0.
    text = re.sub(r'^\s*#.*$', '', text, flags=re.M)
    result = {}
    for table in re.finditer(r'static const TIFFField\s+(\w+)\[\]\s*=\s*\{(.*?)\};', text, re.S):
        rows = []
        for row in re.finditer(r'\{([^{}]+)\}', table[2], re.S):
            m = re.fullmatch(r'\s*(\w+),\s*(-?\w+),\s*(-?\w+),\s*(TIFF_\w+),\s*0,\s*TIFF_SETGET_(\w+),\s*(\w+),\s*(?:\d|TRUE|FALSE),\s*(\d|TRUE|FALSE),\s*(?:\(char\s*\*\)\s*)?"([^"]*)",\s*(?:\(TIFFFieldArray\s*\*\))?[\w&]+\s*', row[1])
            assert m, (path.name, table[1], row[1])
            tag, rc, wc, typ, get, bit, passc, title = m.groups()
            if bit in ('FIELD_IGNORE', 'FIELD_PSEUDO'):
                continue
            base = re.sub('^C(?:0|16|32)_', '', get)
            # Special get/set shapes are explicitly handled in tiff_compat.c.
            # Unknown codec shapes must never silently become anonymous tags.
            assert base in kind or path.name == 'tif_dirinfo.c', (path.name, tag, get)
            host, size = kind.get(base, (typ, 0))
            arr = int(get.startswith('C') or base == 'ASCII')
            cs = 4 if get.startswith('C32_') else 2 if get.startswith('C16_') else 0
            fields = [tag, typ, counts.get(rc, rc), counts.get(wc, wc),
                      {'TRUE': '1', 'FALSE': '0'}.get(passc, passc),
                      str(size), str(cs), str(int(bit == 'FIELD_CUSTOM')),
                      '"' + title + '"', host, str(arr), '0']
            rows.append((tag, '  {' + ','.join(fields) + '},'))
        assert not re.sub(r'\{[^{}]+\}|[\s,]', '', table[2], flags=re.S), (path, table[1])
        result[table[1]] = rows
    return result

standard = tables(source / 'tif_dirinfo.c')
codec = {}
for path in sorted(source.glob('tif_*.c')):
    if path.name == 'tif_dirinfo.c':
        continue
    for rows in tables(path).values():
        for tag, row in rows:
            assert tag not in codec or codec[tag] == row, ('conflicting codec schemas', tag)
            codec[tag] = row
# Pin the full on-file codec inventory, not just the tags a fixture exercises.
assert len(codec) == 15, codec.keys()
assert not set(codec).intersection(tag for tag, _ in standard['tiffFields'])
out = ['/* Declarative standard and codec schemas from libtiff 4.7.1.',
       ' * Copyright (c) 1988-1997 Sam Leffler; (c) 1991-1997 Silicon Graphics.',
       ' * See LICENSE-libtiff.md. Generated by generate_fields.py. */']
for name in ('tiffFields', 'exifFields', 'gpsFields'):
    out.append('static const TIFFField ' + name + '[] = {')
    out.extend(row for _, row in standard[name])
    if name == 'tiffFields':
        out.extend(codec.values())
    out.append('};')
result = '\n'.join(out) + '\n'
p = argparse.ArgumentParser()
p.add_argument('--check', action='store_true')
args = p.parse_args()
output = root / 'compat/field_schemas.inc'
if args.check:
    assert output.read_text() == result, 'field_schemas.inc is stale; run compat/generate_fields.py'
else:
    output.write_text(result)
print(f'Field schemas: {len(standard["tiffFields"])} base, {len(codec)} codec, '
      f'{len(standard["exifFields"])} EXIF, {len(standard["gpsFields"])} GPS')
