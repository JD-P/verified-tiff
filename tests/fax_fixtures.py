def run(n,color):
    t=BLACK if color else WHITE;out=''
    while n>=2560:out+=t[2560];n-=2560
    if n>=64:q=n//64*64;out+=t[q];n-=q
    return out+t[n]

def one_d(row):
    out='';color=0;start=0
    for i in range(len(row)+1):
        if i==len(row) or row[i]!=color:
            out+=run(i-start,color);start=i;color^=1
    return out

