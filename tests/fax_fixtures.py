def encode(rows,group=4,mixed=False,aligned=False,missing=False,fill=1,terminate=True):
    bits='';reference=[0]*len(rows[0])
    def eol():return '0'*((-(len(bits)+12))%8 if aligned else 0)+'000000000001'
    for y,row in enumerate(rows):
        td=group==4 or (mixed and y%3!=0)
        if group==3 and not missing:
            bits+=eol()
            if mixed:bits+='0' if td else '1'
        bits+=two_d(row,reference) if td else one_d(row);reference=row
    if terminate and not missing:
        for _ in range(2 if group==4 else 6):bits+=eol()+('1' if mixed and group==3 else '')
    return pack(bits,fill)

def pack(bits,fill=1):
    bits+='0'*(-len(bits)%8)
    return bytes(int(bits[i:i+8][::-1] if fill==2 else bits[i:i+8],2) for i in range(0,len(bits),8))

